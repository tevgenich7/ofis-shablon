#!/bin/bash
# Настройка офиса на ЭТОМ компьютере. Запускать один раз после установки и после переноса папки.
# Ничего не скачивает, пишет только внутрь папки офиса.
# Что делает: ставит охранника на отправку копий (.git/hooks/pre-push). Сторожа Codex
# (.codex/hooks.json) переделывать не нужно: путь к ним берётся от корня папки через git,
# файл один и тот же на любом компьютере.
set -e
KOREN="$(cd "$(dirname "$0")/.." && pwd)"
if [ -d "$KOREN/.git" ]; then
  mkdir -p "$KOREN/.git/hooks"
  cp "$KOREN/scripts/git-hooks/pre-push" "$KOREN/.git/hooks/pre-push"
  chmod +x "$KOREN/.git/hooks/pre-push"
  echo "Готово: охранник на отправку копий поставлен (.git/hooks/pre-push)"
else
  echo "Папка офиса без git - охранник на отправку копий не нужен, копий не будет"
fi
echo "Сторожа Codex уже на месте (.codex/hooks.json). Панель и бот включают их сами."
echo "Если открываешь офис в чёрном окне командой codex - один раз набери /hooks и одобри оба пункта."
